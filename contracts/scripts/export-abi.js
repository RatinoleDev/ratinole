// Writes the ABIs the engine, API and web app use into packages/config/src/abi.ts, straight from the compiled
// contracts, so the app can never drift from what is deployed. Run after changing a contract:
//   pnpm --filter @rationale/contracts exec hardhat compile && node contracts/scripts/export-abi.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const read = (name) => JSON.parse(fs.readFileSync(path.join(root, "artifacts", "contracts", `${name}.sol`, `${name}.json`), "utf8")).abi;

const ERC20 = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "string" }] },
  {
    type: "function",
    name: "transfer",
    stateMutability: "nonpayable",
    inputs: [{ name: "to", type: "address" }, { name: "amount", type: "uint256" }],
    outputs: [{ name: "", type: "bool" }],
  },
];

const out = `/**
 * Contract ABIs, generated by contracts/scripts/export-abi.js from the compiled contracts. Do not edit by hand.
 */
export const VAULT_ABI = ${JSON.stringify(read("AgentVault"))} as const;

export const FACTORY_ABI = ${JSON.stringify(read("AgentVaultFactory"))} as const;

export const REGISTRY_ABI = ${JSON.stringify(read("DecisionRegistry"))} as const;

export const ERC20_ABI = ${JSON.stringify(ERC20)} as const;
`;
fs.writeFileSync(path.join(root, "..", "packages", "config", "src", "abi.ts"), out);
console.log("wrote packages/config/src/abi.ts");
